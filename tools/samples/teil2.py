R("Spaghetti mit Tomatensauce", 4, 30, "hauptgerichte, vegetarisch, schnell", """
500 g Spaghetti
2 EL Olivenöl
1 Zwiebel
2 Knoblauchzehen
800 g stückige Tomaten (Dose)
1 TL getrockneter Oregano
1 TL Zucker
1 Prise Salz
1 Prise Pfeffer
1/2 Bund Basilikum
60 g Parmesan
""", """
1. Zwiebel und Knoblauch fein würfeln und im Öl glasig dünsten.
2. Tomaten, Oregano, Zucker, Salz und Pfeffer zugeben und offen 20 Minuten köcheln lassen.
3. Inzwischen die Spaghetti in reichlich Salzwasser bissfest kochen.
4. Sauce mit zerzupftem Basilikum abschmecken, mit den Nudeln mischen und mit geriebenem Parmesan servieren.
""")

R("Gemüselasagne", 6, 90, "hauptgerichte, vegetarisch", """
2 Zucchini
1 Aubergine
2 rote Paprikaschoten
1 Zwiebel
2 Knoblauchzehen
2 EL Olivenöl
800 g stückige Tomaten (Dose)
1 Prise Salz
1 Prise Pfeffer
50 g Butter
50 g Weizenmehl
600 ml Milch
1 Prise Muskat
250 g Lasagneplatten
150 g geriebener Gouda
""", """
1. Gemüse klein würfeln, Zwiebel und Knoblauch hacken. Im Öl 10 Minuten anbraten, Tomaten zugeben, salzen, pfeffern und 10 Minuten köcheln lassen.
2. Für die Béchamel die Butter schmelzen, Mehl einrühren und kurz anschwitzen. Nach und nach die Milch einrühren und 5 Minuten köcheln lassen. Mit Salz und Muskat würzen.
3. Backofen auf 180 °C Umluft vorheizen. In eine Auflaufform abwechselnd Gemüsesauce, Lasagneplatten und Béchamel schichten, mit Béchamel abschließen.
4. Mit Käse bestreuen und 40 Minuten backen, bis die Oberfläche goldbraun ist. 10 Minuten ruhen lassen.
""")

R("Kartoffelgratin", 4, 75, "hauptgerichte, vegetarisch, beilagen, winter", """
1 kg festkochende Kartoffeln
1 Knoblauchzehe
1 EL Butter
200 ml Sahne
200 ml Milch
100 g geriebener Emmentaler
1 Prise Muskat
1 Prise Salz
1 Prise Pfeffer
""", """
1. Backofen auf 180 °C Umluft vorheizen. Eine Auflaufform mit der halbierten Knoblauchzehe ausreiben und mit Butter einfetten.
2. Kartoffeln schälen und in dünne Scheiben hobeln. Dachziegelartig in die Form schichten.
3. Sahne und Milch mit Muskat, Salz und Pfeffer verrühren und darübergießen.
4. Mit Käse bestreuen und etwa 50 Minuten backen, bis die Kartoffeln weich sind.
""")

R("Käsespätzle", 4, 40, "hauptgerichte, vegetarisch", """
400 g Weizenmehl
4 Eier
150 ml Wasser
1 Prise Salz
3 Zwiebeln
2 EL Butter
200 g geriebener Bergkäse
1/2 Bund Schnittlauch
1 Prise Pfeffer
""", """
1. Mehl, Eier, Wasser und Salz zu einem zähen Teig schlagen, bis er Blasen wirft. 10 Minuten ruhen lassen.
2. Zwiebeln in Ringe schneiden und in der Butter langsam goldbraun rösten.
3. Teig portionsweise durch eine Spätzlepresse in kochendes Salzwasser drücken. Sobald die Spätzle oben schwimmen, mit einer Schaumkelle herausnehmen.
4. Spätzle schichtweise mit dem Käse in eine warme Form geben, zuletzt die Röstzwiebeln darauf. Mit Pfeffer und Schnittlauch servieren.
""")

