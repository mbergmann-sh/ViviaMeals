# ---------------------------------------------------------------- Backen
R("Apfelkuchen vom Blech", 20, 75, "backen, kuchen, vegetarisch, herbst", """
250 g weiche Butter
200 g Zucker
1 Päckchen Vanillezucker
5 Eier
400 g Weizenmehl
1 Päckchen Backpulver
100 ml Milch
1,5 kg säuerliche Äpfel
1 Zitrone
1 TL Zimt
2 EL Zucker
""", """
1. Backofen auf 180 °C Ober-/Unterhitze vorheizen und ein Blech mit Backpapier auslegen.
2. Butter mit Zucker und Vanillezucker cremig schlagen, Eier einzeln unterrühren. Mehl mit Backpulver mischen und abwechselnd mit der Milch unterrühren.
3. Teig auf dem Blech glatt streichen. Äpfel schälen, vierteln, entkernen, mehrfach einritzen und mit Zitronensaft beträufeln.
4. Äpfel dicht an dicht in den Teig setzen, mit Zimt und Zucker bestreuen und etwa 40 Minuten backen.
""", unit="Stücke")

R("Marmorkuchen", 16, 80, "backen, kuchen, vegetarisch", """
250 g weiche Butter
250 g Zucker
1 Päckchen Vanillezucker
5 Eier
375 g Weizenmehl
1 Päckchen Backpulver
125 ml Milch
2 EL Kakaopulver
2 EL Milch
1 EL Puderzucker
""", """
1. Backofen auf 175 °C Ober-/Unterhitze vorheizen, eine Gugelhupfform fetten und mit Mehl ausstäuben.
2. Butter, Zucker und Vanillezucker schaumig schlagen, Eier einzeln unterrühren. Mehl und Backpulver abwechselnd mit 125 ml Milch unterheben.
3. Die Hälfte des Teigs in die Form füllen. Unter den Rest Kakao und 2 EL Milch rühren und darauf verteilen. Mit einer Gabel spiralförmig durchziehen.
4. Etwa 55 Minuten backen (Stäbchenprobe), auskühlen lassen und mit Puderzucker bestäuben.
""", unit="Stücke")

