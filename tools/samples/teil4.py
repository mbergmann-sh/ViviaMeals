R("Vollkornbrötchen", 8, 120, "backen, brot, vegan", """
500 g Weizenvollkornmehl
1 Päckchen Trockenhefe
350 ml lauwarmes Wasser
1 TL Salz
1 EL Ahornsirup
2 EL Sonnenblumenkerne
2 EL Haferflocken
""", """
1. Mehl, Hefe, Wasser, Salz und Ahornsirup 8 Minuten zu einem weichen Teig kneten. Abgedeckt 1 Stunde gehen lassen.
2. Teig in 8 Stücke teilen, rund formen, mit Wasser bestreichen und in Sonnenblumenkernen und Haferflocken wälzen.
3. Auf einem Blech weitere 20 Minuten gehen lassen. Backofen auf 220 °C Ober-/Unterhitze vorheizen.
4. Brötchen 20 Minuten backen, dabei eine Tasse Wasser auf den Ofenboden stellen.
""", unit="Stück")

