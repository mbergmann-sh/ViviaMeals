R("Bircher-Müsli mit Apfel", 2, 10, "frühstück, schnell", """
80 g zarte Haferflocken
150 ml Milch
150 g Naturjoghurt
1 Apfel
1 EL Zitronensaft
1 EL Honig
2 EL gehackte Haselnüsse
100 g Heidelbeeren
""", """
1. Haferflocken mit Milch und Joghurt verrühren und abgedeckt mindestens 30 Minuten, besser über Nacht, im Kühlschrank quellen lassen.
2. Den Apfel waschen, mit Schale grob reiben und sofort mit dem Zitronensaft mischen.
3. Apfel und Honig unter die Haferflocken rühren. Ist das Müsli zu fest, einen Schuss Milch zugeben.
4. In Schalen füllen, mit Heidelbeeren und Haselnüssen bestreuen.
""")

R("Rührei mit Schnittlauch", 2, 10, "frühstück, schnell", """
4 Eier
3 EL Milch
1 TL Butter
1/2 Bund Schnittlauch
1 Prise Salz
1 Prise Pfeffer
2 Scheiben Vollkornbrot
""", """
1. Eier mit Milch, Salz und Pfeffer in einer Schüssel verquirlen.
2. Schnittlauch waschen, trocken schütteln und in feine Röllchen schneiden.
3. Butter in einer beschichteten Pfanne bei mittlerer Hitze schmelzen. Die Eimasse hineingeben und kurz stocken lassen.
4. Mit einem Pfannenwender immer wieder vom Rand zur Mitte schieben, bis das Ei cremig gestockt ist – nicht zu trocken werden lassen.
5. Schnittlauch unterheben und sofort mit dem Brot servieren.
""")

