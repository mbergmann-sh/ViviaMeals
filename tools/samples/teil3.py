R("Schweinebraten mit Kruste", 6, 180, "hauptgerichte, fleischgerichte, winter", """
1,5 kg Schweinebraten mit Schwarte
1 Prise Salz
1 Prise Pfeffer
1 TL Kümmel
2 Zwiebeln
2 Möhren
1/2 Knollensellerie
500 ml dunkles Bier
500 ml Rinderbrühe
1 EL Speisestärke
""", """
1. Backofen auf 180 °C Ober-/Unterhitze vorheizen. Schwarte rautenförmig einschneiden, ohne das Fleisch zu verletzen. Fleisch rundum mit Salz, Pfeffer und Kümmel einreiben.
2. Gemüse grob würfeln, in einen Bräter geben und den Braten mit der Schwarte nach unten daraufsetzen. Mit der Hälfte von Bier und Brühe aufgießen und 1 Stunde garen.
3. Braten wenden, restliche Flüssigkeit zugeben und weitere 80 Minuten garen, dabei gelegentlich mit Bratensaft übergießen.
4. Für die Kruste die letzten 15 Minuten den Grill einschalten, bis die Schwarte aufpoppt.
5. Sauce passieren, mit Stärke binden und abschmecken. Dazu passen Knödel und Krautsalat.
""")

