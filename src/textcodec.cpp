QString decode(const QByteArray &input, QString *detected)
{
    QByteArray data = input;
    if (data.startsWith("\xEF\xBB\xBF")) data = data.mid(3);
    if (validUtf8(data)) {
        if (detected) *detected = QStringLiteral("UTF-8");
        return QString::fromUtf8(data);
    }
    // Umlaut-Bytes zählen
    int dos = 0, win = 0;
    for (char ch : data) {
        const unsigned char c = static_cast<unsigned char>(ch);
        if (c == 0x81 || c == 0x84 || c == 0x94 || c == 0x8E || c == 0x99 || c == 0x9A || c == 0xE1) ++dos;
        if (c == 0xE4 || c == 0xF6 || c == 0xFC || c == 0xDF || c == 0xC4 || c == 0xD6 || c == 0xDC) ++win;
    }
    const bool cp850 = dos > win;
    if (detected) *detected = cp850 ? QStringLiteral("CP850") : QStringLiteral("Windows-1252");
    QString out;
    out.reserve(data.size());
    for (char ch : data) {
        const unsigned char c = static_cast<unsigned char>(ch);
        if (c < 0x80) out += QChar(c);
        else if (cp850) out += QChar(kCp850[c - 0x80]);
        else if (c < 0xA0) out += QChar(kCp1252[c - 0x80]);
        else out += QChar(c);
    }
    return out;
}

QString readFile(const QString &path, QString *error, QString *detected)
{
    QFile f(path);
    if (!f.open(QIODevice::ReadOnly)) {
        if (error) *error = f.errorString();
        return {};
    }
    QString s = decode(f.readAll(), detected);
    s.replace(QStringLiteral("\r\n"), QStringLiteral("\n"));
    s.replace(QLatin1Char('\r'), QLatin1Char('\n'));
    return s;
}

